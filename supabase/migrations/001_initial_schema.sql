-- Durable case state and the exact conversation/agent audit trail

create table if not exists public.cases (
  id uuid primary key default gen_random_uuid(),
  public_id text not null unique default (
    'MC-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8))
  ),
  status text not null default 'new',
  channel text not null default 'portal',
  unit text,
  summary text,
  issue_category text,
  problem_code text,
  urgency text,
  vendor_trade text,
  safety_flag boolean not null default false,
  safety_reason text,
  missing_info jsonb not null default '[]'::jsonb,
  offered_slots jsonb not null default '[]'::jsonb,
  appointment jsonb,
  citations jsonb not null default '[]'::jsonb,
  escalation_reason text,
  current_response text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint cases_status_check check (
    status in ('new', 'needs_info', 'awaiting_tenant', 'scheduled', 'escalated', 'resolved')
  ),
  constraint cases_channel_check check (
    channel in ('whatsapp', 'sms', 'email', 'portal')
  ),
  constraint cases_urgency_check check (
    urgency is null or urgency in ('EMERGENCY', 'URGENT', 'ROUTINE')
  ),
  constraint cases_missing_info_array_check check (jsonb_typeof(missing_info) = 'array'),
  constraint cases_offered_slots_array_check check (jsonb_typeof(offered_slots) = 'array'),
  constraint cases_citations_array_check check (jsonb_typeof(citations) = 'array'),
  constraint cases_metadata_object_check check (jsonb_typeof(metadata) = 'object')
);

create index if not exists cases_status_updated_at_idx
  on public.cases (status, updated_at desc);

drop trigger if exists cases_set_updated_at on public.cases;
create trigger cases_set_updated_at
before update on public.cases
for each row execute function public.set_updated_at();

create table if not exists public.messages (
