-- no anon/authenticated policies are created. The backend secret key assumes
-- service_role and is the only application credential allowed to access data.

alter table public.hpd_taxonomy enable row level security;
alter table public.cases enable row level security;
alter table public.messages enable row level security;
alter table public.case_events enable row level security;
alter table public.rag_documents enable row level security;
alter table public.rag_chunks enable row level security;
alter table public.vendors enable row level security;
alter table public.vendor_slots enable row level security;
alter table public.appointments enable row level security;

revoke all on function public.search_hpd_taxonomy(text, integer)
  from public, anon, authenticated;
grant execute on function public.search_hpd_taxonomy(text, integer)
  to service_role;

revoke all on function public.append_case_event(
  uuid, text, text, jsonb, jsonb, text, text, jsonb
) from public, anon, authenticated;
grant execute on function public.append_case_event(
  uuid, text, text, jsonb, jsonb, text, text, jsonb
) to service_role;

commit;
