create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Structured HPD taxonomy (loaded from the grouped CSV in a later step)

create table if not exists public.hpd_taxonomy (
  id bigint generated by default as identity primary key,
  major_category text not null,
  minor_category text not null default '',
  problem_code text not null,
  raw_type text not null,
  urgency text not null,
  complaint_count bigint not null default 0,
  search_text text generated always as (
    lower(
      coalesce(major_category, '') || ' ' ||
      coalesce(minor_category, '') || ' ' ||
      coalesce(problem_code, '')
    )
  ) stored,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  constraint hpd_taxonomy_raw_type_check check (
    raw_type in ('IMMEDIATE EMERGENCY', 'EMERGENCY', 'HAZARDOUS', 'NON EMERGENCY')
  ),
  constraint hpd_taxonomy_urgency_check check (
    urgency in ('EMERGENCY', 'URGENT', 'ROUTINE')
  ),
  constraint hpd_taxonomy_count_check check (complaint_count >= 0),
  constraint hpd_taxonomy_source_row_unique unique (
    major_category, minor_category, problem_code, raw_type
  )
);

create index if not exists hpd_taxonomy_search_text_trgm_idx
  on public.hpd_taxonomy using gin (search_text extensions.gin_trgm_ops);

create index if not exists hpd_taxonomy_problem_code_idx
  on public.hpd_taxonomy (problem_code);

create index if not exists hpd_taxonomy_urgency_count_idx
  on public.hpd_taxonomy (urgency, complaint_count desc);

drop trigger if exists hpd_taxonomy_set_updated_at on public.hpd_taxonomy;
create trigger hpd_taxonomy_set_updated_at
before update on public.hpd_taxonomy
for each row execute function public.set_updated_at();

-- Fuzzy structured search used by the taxonomy tool. The table is small
-- (641 source rows), so ordering all rows by trigram similarity is predictable
-- and avoids returning no candidates for vague tenant language.
create or replace function public.search_hpd_taxonomy(
  query_text text,
  match_count integer default 5
)
returns table (
  id bigint,
  major_category text,
  minor_category text,
  problem_code text,
  raw_type text,
  urgency text,
  complaint_count bigint,
  similarity_score real
)
language sql
stable
security invoker
set search_path = public, extensions
as $$
  select
    taxonomy.id,
    taxonomy.major_category,
    taxonomy.minor_category,
    taxonomy.problem_code,
    taxonomy.raw_type,
    taxonomy.urgency,
    taxonomy.complaint_count,
    extensions.similarity(
      taxonomy.search_text,
      lower(trim(query_text))
    )::real as similarity_score
  from public.hpd_taxonomy as taxonomy
  where query_text is not null
    and trim(query_text) <> ''
  order by
    extensions.similarity(taxonomy.search_text, lower(trim(query_text))) desc,
    taxonomy.complaint_count desc,
    taxonomy.id
  limit greatest(1, least(coalesce(match_count, 5), 20));
$$;

